'use client'

import { useEffect, useState } from 'react'

interface ReadingEventsSummary {
  opens: number
  finished: boolean
  pagesSeen: number
  replays: number
  quizAttempts: number
  quizAccuracy: number | null
  readAlongSamples: number
  readAlongAccuracy: number | null
  lastReadAt: string | null
}

interface ProgressReportProps {
  /** 传给页面的稳定标识，用于生成可分享链接 */
  shareId: string
  /** 家长显示的名字（脱敏后） */
  childName?: string
  bookTitle: string
  level?: string
  ageGroup?: string
  pageCount?: number
}

/**
 * 可分享的成长报告。
 *
 * 学情数据本身是私有的（只给本家庭看），但报告是家长主动分享给
 * 老师/亲戚/其他家长的 —— 内容全部来自已存储的阅读事件，
 * 不包含任何身份信息，只有聚合后的数字。
 */
export default function ProgressReport({
  shareId,
  childName,
  bookTitle,
  level,
  ageGroup,
  pageCount,
}: ProgressReportProps) {
  const [data, setData] = useState<ReadingEventsSummary | null>(null)
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    if (!shareId) return
    let alive = true
    fetch(`/api/analytics/book?bookId=${shareId}`)
      .then((r) => (r.ok ? r.json() : null))
      .then((d) => {
        if (alive && d) setData(d)
      })
      .catch(() => {})
    return () => {
      alive = false
    }
  }, [shareId])

  const handleCopy = async () => {
    const url = `${window.location.origin}/progress`
    try {
      await navigator.clipboard.writeText(url)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      setCopied(false)
    }
  }

  const handlePrint = () => {
    window.print()
  }

  const rows = data
    ? [
        { label: 'Times opened', value: String(data.opens) },
        { label: 'Finished', value: data.finished ? 'Yes' : 'Not yet' },
        { label: 'Pages read', value: String(data.pagesSeen) },
        { label: 'Replays', value: String(data.replays) },
        { label: 'Quiz accuracy', value: data.quizAccuracy === null ? '—' : `${Math.round(data.quizAccuracy * 100)}%` },
        {
          label: 'Read-aloud accuracy',
          value: data.readAlongAccuracy === null ? '—' : `${Math.round(data.readAlongAccuracy * 100)}%`,
        },
      ]
    : []

  return (
    <div className="apple-card p-6 md:p-8 print:shadow-none print:border-0">
      <div className="flex items-start justify-between gap-4 mb-5">
        <div>
          <h2 className="text-lg font-bold text-[#2D2D2D]">Growth report</h2>
          <p className="text-xs text-[#8E8E93] mt-0.5">
            A shareable snapshot of how this reader is doing.
          </p>
        </div>
        <div className="flex gap-2 print:hidden">
          <button onClick={handleCopy} className="apple-button-secondary text-xs px-3 py-2">
            {copied ? '✓ Copied' : 'Copy link'}
          </button>
          <button onClick={handlePrint} className="apple-button-secondary text-xs px-3 py-2">
            Print
          </button>
        </div>
      </div>

      {/* 报告抬头 */}
      <div className="rounded-2xl bg-[#FAFAFB] p-5 mb-5">
        <p className="text-xs uppercase tracking-wide text-[#8E8E93]">Reading record</p>
        <p className="mt-1 text-lg font-bold text-[#2D2D2D]">
          {childName || 'Young reader'}
          {childName ? '' : ''}
        </p>
        <p className="text-sm text-[#8E8E93] mt-0.5">{bookTitle}</p>
        <div className="mt-3 flex flex-wrap gap-2">
          {level && (
            <span className="inline-flex items-center px-2.5 py-1 rounded-full bg-[#FFF5EE] text-[#FF6B8A] text-xs font-semibold">
              GRL {level}
            </span>
          )}
          {ageGroup && (
            <span className="inline-flex items-center px-2.5 py-1 rounded-full bg-[#F2F2F7] text-[#8E8E93] text-xs">
              {ageGroup} years
            </span>
          )}
          {pageCount !== undefined && (
            <span className="inline-flex items-center px-2.5 py-1 rounded-full bg-[#98D8C8]/20 text-[#4A9E8E] text-xs">
              {pageCount} pages
            </span>
          )}
        </div>
      </div>

      {data ? (
        <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
          {rows.map((r) => (
            <div key={r.label} className="rounded-xl bg-[#FAFAFB] px-4 py-3">
              <p className="text-[11px] uppercase tracking-wide text-[#8E8E93]">{r.label}</p>
              <p className="mt-1 text-lg font-bold text-[#2D2D2D]">{r.value}</p>
            </div>
          ))}
        </div>
      ) : (
        <p className="text-sm text-[#8E8E93]">No reading recorded yet.</p>
      )}

      <p className="mt-5 text-[11px] text-[#8E8E93] print:mt-4">
        Generated by SproutTales. Only aggregate reading numbers are included — no names, photos or
        identifying details.
      </p>
    </div>
  )
}
